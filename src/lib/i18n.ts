export function translateStatic(language: AppLanguage, text: string): string {
  if (language === "nl") {
    return text;
  }

  return staticTranslations[text] ?? text;
}

export function getWeekdayLabels(language: AppLanguage): Record<Weekday, string> {
  return weekdayLabelsByLanguage[language];
}

export function getMonthLabels(language: AppLanguage): string[] {
  return monthLabelsByLanguage[language];
}

export function getLocale(language: AppLanguage): string {
  return localeByLanguage[language];
}

export function translateStatus(language: AppLanguage, status: AppStatus): string {
  if (language === "nl") {
    if (status === "open") return "Open";
    if (status === "bezig") return "Bezig";
    return "Klaar";
  }

  if (status === "open") return "Open";
  if (status === "bezig") return "Busy";
  return "Done";
}
